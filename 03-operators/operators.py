# Operator are used to Do mathetical Operations 

num_1 = 100
num_2 = 200

# 1) Artithmatic Operator
print(num_1 + num_2) # Addition 
print(num_1 - num_2) # Subtraction 
print(num_1 * num_2) # Multiply 
print(num_1 / num_2) # Divide
print(num_1 % num_2) # Modulo (Remainder)

# 2) Relational Operator 
print(num_1 < num_2) # Less Than 
print(num_1 > num_2) # Greater Than
print(num_1 <= num_2) # Less Than = 
print(num_1 >= num_2) # Greater Than = 
print(num_1 == num_2) # Equal too
print(num_1 !=  num_2) # Not Equal Too

# 3) Assignment Operator
num_1 = num_2 # Assign Value 
print(num_2)
num_2 += num_1 # Add Into Value 
print(num_2)
num_2 -= num_1 # Subtract From Value 
print(num_2)
num_2 *= num_1  # Multiply From Value
print(num_2)
num_2 <<= num_1 #
print(num_2)

# 4) Logical Operator 

# 1) AND Operator Truth Table
print("AND Operator")
print("True and True =", True and True)
print("True and False =", True and False)
print("False and True =", False and True)
print("False and False =", False and False)

# 2) OR Operator Truth Table
print("\nOR Operator")
print("True or True =", True or True)
print("True or False =", True or False)
print("False or True =", False or True)
print("False or False =", False or False)

# 3) NOT Operator Truth Table
print("\nNOT Operator")
print("not True =", not True)
print("not False =", not False)

 